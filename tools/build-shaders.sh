#!/usr/bin/env sh
# Compile src/shaders/*.cg with the official psp2cgc under wine, and write the
# binaries into src/shaders/gxm_shaders.h as C arrays. The header is committed,
# so the normal build does not need wine. Run this after editing a .cg file.
# Files ending in _v.cg are vertex programs; files ending in _f.cg are fragment
# programs.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
CGC=${FZERO_PSP2CGC_EXE:-/usr/local/vitasdk/official_sdk/host_tools/bin/psp2cgc.exe}
DIR=$ROOT/src/shaders
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
for src in "$DIR"/*.cg; do
    name=$(basename "$src" .cg)
    case $name in
        *_v) profile=sce_vp_psp2 ;;
        *_f) profile=sce_fp_psp2 ;;
        *) echo "unknown shader kind: $name" >&2; exit 1 ;;
    esac
    # ground_f does integer work in fp32 and must be exact. At the default
    # precision the compiler may pick a sequence that is not, and which one
    # depends on the surrounding code.
    flags=
    case $name in ground_f) flags=-bestprecision ;; esac
    (cd "$DIR" && wine "$CGC" -profile "$profile" $flags "$name.cg" -o "$TMP/$name.gxp") \
        >"$TMP/$name.log" 2>&1 || { cat "$TMP/$name.log" >&2; exit 1; }
    [ -s "$TMP/$name.gxp" ] || { cat "$TMP/$name.log" >&2; exit 1; }
done
python3 - "$TMP" "$DIR/gxm_shaders.h" <<'PY'
import os, sys
tmp, out = sys.argv[1], sys.argv[2]
lines = ["/* Generated by tools/build-shaders.sh from src/shaders/*.cg. Do not edit. */",
         "#pragma once", "#include <stdint.h>", ""]
for f in sorted(os.listdir(tmp)):
    if not f.endswith(".gxp"):
        continue
    data = open(os.path.join(tmp, f), "rb").read()
    name = "g_gxp_" + f[:-4]
    lines.append("static const uint8_t %s[%d] __attribute__((aligned(16))) = {" % (name, len(data)))
    for i in range(0, len(data), 12):
        lines.append("    " + " ".join("0x%02x," % b for b in data[i:i + 12]))
    lines.append("};")
    lines.append("")
open(out, "w").write("\n".join(lines))
PY
echo "wrote $DIR/gxm_shaders.h"
